package gateway

import (
	"context"
	"net"
	"strconv"

	corev1 "k8s.io/api/core/v1"
	apierrors "k8s.io/apimachinery/pkg/api/errors"
	"k8s.io/apimachinery/pkg/types"
	"sigs.k8s.io/controller-runtime/pkg/client"

	workspacesv1alpha1 "github.com/nekomeowww/rc/apis/kubernetes/workspaces/v1alpha1"
	"github.com/nekomeowww/rc/internal/datad/pki"
	datadssh "github.com/nekomeowww/rc/internal/datad/sandbox/protocol/ssh"
	"github.com/nekomeowww/rc/pkg/envd"
	"github.com/nekomeowww/rc/pkg/execd"
)

// DefaultAccessTokenSecretKey is the default Secret key storing a Workspace's
// Data Plane access token when generated by the controller.
const DefaultAccessTokenSecretKey = "token"

// DefaultAuthorizedKeysSecretKey is the default Secret key storing newline-separated
// OpenSSH authorized_keys entries for Workspace SSH access.
const DefaultAuthorizedKeysSecretKey = "authorized_keys"

// KubernetesResolver resolves Workspace Data Plane targets directly from the
// Kubernetes API (Workspaces, runtime Pods, and token Secrets).
type KubernetesResolver struct {
	Client    client.Reader
	ExecdPort int32
	Port      int32
	SSHPort   int32
}

// Resolve looks up the Workspace, its access token Secret, and its runtime Pod IP.
func (r *KubernetesResolver) Resolve(ctx context.Context, namespace, name string) (Target, error) {
	ws := &workspacesv1alpha1.Workspace{}
	if err := r.Client.Get(ctx, types.NamespacedName{Namespace: namespace, Name: name}, ws); err != nil {
		if apierrors.IsNotFound(err) {
			return Target{}, ErrNotFound
		}
		return Target{}, err
	}
	if ws.Spec.DataPlane == nil || !ws.Spec.DataPlane.Enabled {
		return Target{}, ErrNotFound
	}

	secretName := ""
	secretKey := DefaultAccessTokenSecretKey
	if ws.Spec.DataPlane.AccessTokenSecretRef != nil {
		secretName = ws.Spec.DataPlane.AccessTokenSecretRef.Name
		if ws.Spec.DataPlane.AccessTokenSecretRef.Key != "" {
			secretKey = ws.Spec.DataPlane.AccessTokenSecretRef.Key
		}
	} else if ws.Status.DataPlane != nil {
		secretName = ws.Status.DataPlane.AccessTokenSecretName
	}

	token := ""
	if secretName != "" {
		secret := &corev1.Secret{}
		if err := r.Client.Get(ctx, types.NamespacedName{Namespace: namespace, Name: secretName}, secret); err != nil {
			if !apierrors.IsNotFound(err) {
				return Target{}, err
			}
		} else {
			token = string(secret.Data[secretKey])
		}
	}

	target := Target{
		Namespace:   namespace,
		Name:        name,
		State:       string(ws.Spec.DesiredState),
		ServerName:  pki.WorkspaceServerName(namespace, name),
		AccessToken: token,
	}
	if ws.Spec.DataPlane.SSH != nil && ws.Spec.DataPlane.SSH.Enabled {
		target.SSHEnabled = true
		if len(ws.Spec.DataPlane.SSH.AuthorizedKeys) > 0 {
			target.SSHAuthorizedKeys = append(target.SSHAuthorizedKeys, ws.Spec.DataPlane.SSH.AuthorizedKeys...)
		}
		if ref := ws.Spec.DataPlane.SSH.AuthorizedKeysSecretRef; ref != nil && ref.Name != "" {
			key := ref.Key
			if key == "" {
				key = DefaultAuthorizedKeysSecretKey
			}
			secret := &corev1.Secret{}
			if err := r.Client.Get(ctx, types.NamespacedName{Namespace: namespace, Name: ref.Name}, secret); err != nil {
				if !apierrors.IsNotFound(err) {
					return Target{}, err
				}
			} else if raw := secret.Data[key]; len(raw) > 0 {
				target.SSHAuthorizedKeys = append(target.SSHAuthorizedKeys, string(raw))
			}
		}
	}
	if ws.Spec.DesiredState == workspacesv1alpha1.WorkspaceDesiredStateSuspended || ws.Status.RuntimePodName == "" {
		return target, nil
	}

	pod := &corev1.Pod{}
	if err := r.Client.Get(ctx, types.NamespacedName{Namespace: namespace, Name: ws.Status.RuntimePodName}, pod); err != nil {
		if apierrors.IsNotFound(err) {
			target.State = "PodMissing"
			return target, nil
		}
		return Target{}, err
	}
	if pod.Status.PodIP == "" || !isPodReady(pod) {
		target.State = string(pod.Status.Phase)
		return target, nil
	}

	port := r.Port
	if port == 0 {
		port = envd.DefaultPort
	}
	execdPort := r.ExecdPort
	if execdPort == 0 {
		execdPort = execd.DefaultPort
	}
	sshPort := r.SSHPort
	if sshPort == 0 {
		sshPort = datadssh.DefaultPort
	}
	target.Ready = true
	target.ExecdAddress = net.JoinHostPort(pod.Status.PodIP, strconv.Itoa(int(execdPort)))
	target.Address = net.JoinHostPort(pod.Status.PodIP, strconv.Itoa(int(port)))
	if target.SSHEnabled {
		target.SSHAddress = net.JoinHostPort(pod.Status.PodIP, strconv.Itoa(int(sshPort)))
	}
	return target, nil
}

func isPodReady(pod *corev1.Pod) bool {
	for _, cond := range pod.Status.Conditions {
		if cond.Type == corev1.PodReady && cond.Status == corev1.ConditionTrue {
			return true
		}
	}
	return false
}
